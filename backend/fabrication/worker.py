"""Desktop integration only. Reuse the guarded, opt-in runtime; no new algorithms.

Main creates a private UUID job directory and supplies these CLI arguments.
Model downloads, reference answers, external PASS flags and arbitrary profiles
are intentionally not exposed to the renderer.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
ALGORITHM = ROOT / 'benchmarks/fabrication-layer-decomposition/algorithm-v1'
sys.path.insert(0, str(ALGORITHM))
sys.path.insert(0, str(ROOT / 'benchmarks/fabrication-layer-decomposition/tools'))


def write_json(path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


def background(job, mode, model_cache):
    from PIL import Image
    from rgba_handoff import prepare
    source = job / 'input.bin'
    with Image.open(source) as image:
        if image.format not in {'PNG', 'JPEG'} or image.width * image.height > 16_000_000:
            raise ValueError('Only PNG/JPEG up to 16 million pixels is supported')
        image.load()
        if mode == 'embedded-alpha':
            alpha = image.convert('RGBA').getchannel('A')
            if alpha.getextrema() == (255, 255):
                raise ValueError('This image has no transparent foreground; select BiRefNet General')
            model = None
        else:
            sys.path.insert(0, str(ROOT / 'benchmarks/background-removal/scripts'))
            import benchmark_lib as lib
            lib.MODEL_CACHE_ROOT = Path(model_cache).resolve()
            adapter = lib.create_adapter('birefnet-general', allow_model_download=False)
            available = adapter.availability()
            if not available.available:
                raise RuntimeError(available.reason)
            adapter.initialize()
            # Consume only the inferred alpha. Never reuse the old multiplied RGB.
            alpha = adapter.remove(image).getchannel('A')
            model = lib.model_artifact_record('birefnet-general', lib.load_manifest()['birefnet-general'])
        if alpha.getextrema()[1] == 0:
            raise ValueError('No foreground was found')
        alpha.save(job / 'alpha.png')
    derived, handoff = prepare(source.read_bytes(), (job / 'alpha.png').read_bytes())
    (job / 'foreground.png').write_bytes(derived)
    write_json(job / 'foreground-record.json', {
        'mode': mode, 'model': model, 'handoff': handoff,
        'manualConfirmation': 'PENDING_REVIEW',
        'colourMeaning': 'decoded source RGB + explicit alpha; not background decontamination',
    })


def presentation(job):
    """Display only actual, independently reread runtime geometry and work steps."""
    from PIL import Image
    from shapely.geometry import shape
    from rerender import _render_closed
    output = job / 'fabrication'
    result = json.loads((output / 'fabrication-result.json').read_text('utf-8'))
    report = json.loads((output / 'report.json').read_text('utf-8'))
    display = json.loads((output / 'assembly-display.json').read_text('utf-8'))
    if result['schemaVersion'] != 'fabrication.layered-result/1':
        raise ValueError('This result is not a verified layered result; no substitute display is allowed')
    policy = display['monochromeFabrication']
    schedule = policy.get('schedule', policy)
    pieces = {p['id']: p for p in result['payload']['pieces']}
    with Image.open(output / 'rerender.png') as image:
        width, height = image.size
    steps = []
    assets = {'foreground': 'foreground.png', 'design': 'fabrication/observed.png',
              'rerender': 'fabrication/rerender.png', 'pieces': 'fabrication/complete-pieces.svg',
              'hidden': 'fabrication/hidden-domains.png', 'seams': 'fabrication/physical-seams.png',
              'numbers': 'fabrication/piece-references.png', 'base': 'fabrication/whole-base.png'}
    for index, step in enumerate(schedule['steps']):
        selected = [pieces[key] for key in step['pieceIds']]
        full = [{'polygon': shape(p['full']), 'rgb': p['rgb']} for p in selected]
        name = f'step-{index + 1}.png'
        Image.fromarray(_render_closed(full, (height, width))).save(job / name)
        assets[f'step-{index + 1}'] = name
        steps.append({**step, 'asset': f'step-{index + 1}'})
    # Cumulative images are already generated by the runtime's monochrome renderer.
    for index, name in enumerate(display['images']):
        assets[f'assembly-{index + 1}'] = f'fabrication/{name}'
    manifest = {
        'schemaVersion': 'desktop-fabrication-view/1', 'resultSha256': result['identity']['sha256'],
        'sourceSha256': hashlib.sha256((job / 'input.bin').read_bytes()).hexdigest(),
        'width': width, 'height': height, 'pieceCount': len(pieces), 'steps': steps,
        'materialDepth': schedule['actualGeometricOverlapDepth'],
        'stepCount': schedule['monochromeWorkLayerCount'], 'assets': assets,
        'pieces': [{k: p[k] for k in ('id', 'colorSlotId', 'sourceComponentIds')} for p in pieces.values()],
        'geometryStatus': report['qualityAcceptance']['BtoC'],
        'visualAcceptance': 'PENDING', 'manufacturing': 'NOT_EVALUATED',
        'productionExportEligible': False,
    }
    write_json(job / 'view.json', manifest)
    return manifest


def fabricate(job):
    from algorithm_runtime import run_algorithm
    record = json.loads((job / 'foreground-record.json').read_text('utf-8'))
    # Public runtime performs input/output protection and independent disk replay.
    run_algorithm(image_path=job / 'input.bin', saved_alpha_path=job / 'alpha.png',
                  output_root=job / 'fabrication', foreground_source=record['mode'],
                  manual_confirmation='PENDING_REVIEW', profile='aggressive',
                  quality_mode='practical-auto', fabrication_policy='whole-silhouette-base/1')
    presentation(job)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--stage', choices=['background', 'fabrication'], required=True)
    parser.add_argument('--job', type=Path, required=True)
    parser.add_argument('--mode', choices=['birefnet-general', 'embedded-alpha'], required=True)
    parser.add_argument('--model-cache', type=Path)
    args = parser.parse_args()
    job = args.job.resolve(strict=True)
    if job.is_relative_to(ROOT) or not (job / 'input.bin').is_file():
        raise ValueError('Job must be outside the source checkout with a saved input')
    if args.stage == 'background':
        if args.mode == 'birefnet-general' and args.model_cache is None:
            raise ValueError('BiRefNet General model cache is not configured')
        background(job, args.mode, args.model_cache)
    else:
        fabricate(job)


if __name__ == '__main__':
    os.environ.setdefault('OMP_NUM_THREADS', '4')
    main()
