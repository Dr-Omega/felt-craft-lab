// Real renderer decode/JPEG conversion and unavailable-service behavior; no API stubs.
const { createRequire } = require('node:module')
const { resolve, join } = require('node:path')
const { mkdirSync, writeFileSync } = require('node:fs')
const assert = require('node:assert/strict')
const { _electron:electron } = createRequire(resolve('..','node_modules/playwright/package.json'))('playwright')
async function main() {
  const out = resolve(process.argv[2]); mkdirSync(out, { recursive:false })
  const env = {...process.env, AI_GATEWAY_BASE_URL:'http://127.0.0.1:1', FELT_FABRICATION_PYTHON:'', FELT_BACKGROUND_PYTHON:'', FELT_BIREFNET_CACHE:''}; delete env.ELECTRON_RUN_AS_NODE
  const app = await electron.launch({ executablePath:resolve('node_modules/electron/dist/electron.exe'), args:['.',`--user-data-dir=${join(out,'profile')}`,'--use-angle=swiftshader','--enable-unsafe-swiftshader','--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream'],env })
  try {
    const page = await app.firstWindow(); const errors=[]; page.on('pageerror',e=>errors.push(String(e)))
    await page.getByRole('button',{name:'画板 · 创作',exact:true}).click(); await page.setViewportSize({width:960,height:640})
    await page.getByRole('button',{name:'添加图片',exact:true}).click()
    await page.getByLabel('上传创作图片').setInputFiles({name:'broken.png',mimeType:'image/png',buffer:Buffer.from('broken')})
    await page.getByRole('alert').filter({hasText:'无法解码'}).waitFor()
    const jpeg = await page.evaluate(()=>{const c=document.createElement('canvas'); c.width=80;c.height=60;const g=c.getContext('2d');g.fillStyle='#abc';g.fillRect(0,0,80,60);return c.toDataURL('image/jpeg').split(',')[1]})
    await page.getByLabel('上传创作图片').setInputFiles({name:'decode-fixture.jpg',mimeType:'image/jpeg',buffer:Buffer.from(jpeg,'base64')})
    await page.getByRole('heading',{name:'确认这张图片'}).waitFor()
    const dimensions=await page.locator('.upload-preview').evaluate(async img=>{await img.decode();return {width:img.naturalWidth,height:img.naturalHeight}})
    assert.deepEqual(dimensions,{width:80,height:60})
    await page.getByRole('button',{name:'关闭添加图片'}).click()
    await page.getByRole('button',{name:'添加图片',exact:true}).click(); await page.getByRole('button',{name:'语音输入生图'}).click()
    await page.getByRole('button',{name:'开始录音',exact:true}).click(); await page.waitForTimeout(350)
    await page.getByRole('button',{name:'完成录音',exact:true}).click()
    await page.getByText('语音识别暂时用不了。请稍后再试，或先在上面打字。',{exact:true}).waitFor()
    await page.screenshot({path:join(out,'01-service-unavailable.png')})
    await page.getByRole('button',{name:'关闭添加图片'}).click()
    await page.getByRole('button',{name:'添加图片',exact:true}).click()
    await page.getByLabel('上传创作图片').setInputFiles({name:'decode-fixture.jpg',mimeType:'image/jpeg',buffer:Buffer.from(jpeg,'base64')})
    await page.getByRole('button',{name:'确认图片并开始拆分',exact:true}).click()
    await page.getByRole('button',{name:'重试准备图层',exact:true}).waitFor()
    assert.equal(await page.locator('.layer-row').count(),0)
    await page.screenshot({path:join(out,'02-no-runtime-no-fake-layers.png')})
    assert.deepEqual(errors,[])
    writeFileSync(join(out,'checks.json'),JSON.stringify({jpegDecodedDimensions:dimensions,corruptImageRejected:true,unavailableAsrShown:true,unavailableRuntimeNoFakeLayers:true,errors},null,2))
    console.log('UPLOAD_ERROR_PATHS_PASS')
  } finally { await app.close() }
}
main().catch(e=>{console.error(e);process.exitCode=1})
