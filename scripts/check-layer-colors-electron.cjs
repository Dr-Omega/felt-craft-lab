// Reuses a copy of a genuine completed pipeline result. No model or geometry rerun.
const { createRequire } = require('node:module')
const { resolve, join } = require('node:path')
const { mkdirSync, cpSync, readFileSync, writeFileSync } = require('node:fs')
const assert = require('node:assert/strict')
const { _electron: electron } = createRequire(resolve('..', 'node_modules/playwright/package.json'))('playwright')
async function main() {
  const source = resolve(process.argv[2]), evidence = resolve(process.argv[3])
  const job = JSON.parse(readFileSync(join(source, 'desktop-job.json'), 'utf8'))
  const profile = join(evidence, 'profile'); mkdirSync(profile, { recursive: true })
  cpSync(source, join(profile, 'fabrication-jobs', job.id), { recursive: true, errorOnExist: true, force: false })
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  const options = { executablePath: resolve('node_modules/electron/dist/electron.exe'), args: ['.', `--user-data-dir=${profile}`, '--use-angle=swiftshader', '--enable-unsafe-swiftshader'], env }
  let app = await electron.launch(options)
  const errors = []
  try {
    let page = await app.firstWindow(); page.on('pageerror', e => errors.push(String(e)))
    await page.evaluate(id => localStorage.setItem('felt-fabrication-job', id), job.id)
    await page.getByRole('button', { name: '画板 · 创作', exact: true }).click()
    await page.locator('.editor-save-psd').waitFor()
    await page.screenshot({ path: join(evidence,'01-sxy-canvas.png') })
    const ratio = await page.locator('.canvas-wrap').evaluate(e => e.clientWidth / e.clientHeight)
    assert(Math.abs(ratio - 1) < 0.01, 'Canvas distorted')
    if (process.env.E2E_EDITOR === 'true') {
      await page.getByRole('button', { name: '打开素材盒', exact: true }).click()
      await page.locator('.material-card').first().click()
      await page.getByRole('button', { name: '放进作品', exact: true }).click()
      await page.locator('.material-sheet.is-open').waitFor({ state: 'hidden' })
      await page.waitForTimeout(450)
      await page.screenshot({path:join(evidence,'editor-after-add.png')})
      const canvas = await page.locator('.upper-canvas').boundingBox()
      await page.mouse.click(canvas.x+canvas.width/2, canvas.y+canvas.height/2)
      assert.equal(await page.getByRole('dialog', {name:'元素图层编辑',exact:true}).count(),0)
      await page.mouse.dblclick(canvas.x+canvas.width/2, canvas.y+canvas.height/2)
      await page.screenshot({path:join(evidence,'editor-after-double.png')})
      await page.getByRole('button', {name:'编辑元素图层',exact:true}).click()
      const editorPanel = page.getByRole('dialog', {name:'元素图层编辑',exact:true})
      await editorPanel.waitFor()
      await editorPanel.locator('.process-controls').waitFor()
      await page.screenshot({path:join(evidence,'editor-edit-popup.png')})
      assert.equal(await editorPanel.locator('.layer-row').count(),0,'Unprocessed object must not get example layers')
      await page.getByRole('button', {name:'关闭图层编辑',exact:true}).click()
      // Drag through the real Fabric pointer path; no document or geometry injection.
      const beforeDrag = await page.locator('.lower-canvas').evaluate(e => e.toDataURL())
      await page.mouse.move(canvas.x+canvas.width/2, canvas.y+canvas.height/2)
      await page.mouse.down()
      await page.mouse.move(canvas.x+canvas.width/2-55, canvas.y+canvas.height/2+25, {steps:8})
      await page.mouse.up()
      await page.waitForTimeout(200)
      assert.notEqual(await page.locator('.lower-canvas').evaluate(e => e.toDataURL()), beforeDrag)
      await page.mouse.dblclick(canvas.x+canvas.width/2-55, canvas.y+canvas.height/2+25)
      await page.getByRole('button', {name:'编辑元素图层',exact:true}).click()
      await editorPanel.waitFor()
      await page.screenshot({path:join(evidence,'editor-dragged-popup.png')})
      await page.getByRole('button', {name:'关闭图层编辑',exact:true}).click()
      await page.setViewportSize({width:960,height:640})
      await page.screenshot({path:join(evidence,'drawing-compact.png')})
      const compact = await page.locator('.canvas-wrap').boundingBox()
      assert(compact.x>=0 && compact.x+compact.width<=960 && Math.abs(compact.width/compact.height-1)<0.01)
      await page.setViewportSize({width:1440,height:900})
    }
    await page.getByRole('button', { name: '返回书本', exact: true }).click()
    const discard = page.getByRole('button', { name: '直接回去', exact: true })
    if (await discard.count()) await discard.click()
    await page.getByRole('button', { name: '去背景与分层', exact: true }).click()
    await page.getByRole('button', { name: '选择已分层元素', exact: true }).dblclick()
    await page.getByRole('button', { name: '编辑', exact: true }).click()
    const before = await page.evaluate(id => window.electronAPI.fabrication.colors(id), job.id)
    const region = page.getByRole('dialog', { name: '元素图层编辑', exact: true })
    assert.deepEqual(await region.locator('.layer-row').allTextContents().then(rows => rows.map(row => row.match(/第 (\d+) 层/)[1])), ['3','2','1'])
    await region.getByRole('button', { name: /^第 2 层/ }).click()
    await page.getByRole('button', { name: '预设颜色 #7457BB', exact: true }).click()
    await page.getByRole('button', { name: '保存换色', exact: true }).click()
    await page.getByText('换色已保存，重新打开可继续编辑。', { exact: true }).waitFor()
    let after = await page.evaluate(id => window.electronAPI.fabrication.colors(id), job.id)
    assert.equal(after.layers[1].hex, '#7457BB')
    assert.equal(after.layers[0].hex, before.layers[0].hex); assert.equal(after.layers[2].hex, before.layers[2].hex)
    await page.getByRole('spinbutton', { name: 'R', exact: true }).fill('17')
    await page.getByRole('spinbutton', { name: 'R', exact: true }).press('Tab')
    await page.getByRole('spinbutton', { name: 'G', exact: true }).fill('34')
    await page.getByRole('spinbutton', { name: 'G', exact: true }).press('Tab')
    await page.getByRole('spinbutton', { name: 'B', exact: true }).fill('51')
    await page.getByRole('spinbutton', { name: 'B', exact: true }).press('Tab')
    await page.getByRole('button', { name: '保存换色', exact: true }).click()
    await page.getByText('换色已保存，重新打开可继续编辑。', { exact: true }).waitFor()
    after = await page.evaluate(id => window.electronAPI.fabrication.colors(id), job.id)
    assert.equal(after.layers[1].hex, '#112233')
    // Exercise the visible wheel, then restore the explicit RGB used for persistence.
    const wheel = await page.locator('.wheel').boundingBox()
    await page.locator('.wheel').click({ position: { x: wheel.width-10, y: wheel.height/2 } })
    await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b => b.textContent.trim() === '保存换色' && !b.disabled))
    await page.locator('input[type=color]').evaluate(e => { e.value='#112233'; e.dispatchEvent(new Event('input',{ bubbles:true })) })
    await page.getByRole('button', { name: '保存换色', exact: true }).click()
    await page.getByText('换色已保存，重新打开可继续编辑。', { exact: true }).waitFor()
    await page.waitForTimeout(800)
    await page.screenshot({ path: join(evidence,'02-layer-recolor.png') })
    await region.screenshot({ path: join(evidence,'03-color-panel.png') })
    // Position tests use layout-only movement of the same genuine result element, never altered geometry.
    await page.getByRole('button', { name: '关闭图层编辑', exact: true }).click()
    // Layout-only side harness must be above the legacy shell nav; production placement is unchanged.
    await page.locator('.integration-content').evaluate(el => el.style.zIndex='200')
    for (const [side, x] of [['right',40], ['left',1100]]) {
      await page.setViewportSize({ width: 1440, height: 900 })
      await page.locator('.inline-color-object').evaluate((el,x) => { el.style.cssText=`position:fixed;left:${x}px;top:170px;width:200px;height:350px;flex:none;z-index:200` },x)
      await page.getByRole('button', { name: '选择已分层元素', exact: true }).dblclick()
      await page.getByRole('button', { name: '编辑', exact: true }).click()
      assert.equal(await region.getAttribute('data-side'),side)
      const box = await region.boundingBox(); assert(box.x >= 12 && box.x + box.width <= 1428)
      await page.screenshot({ path:join(evidence,`panel-${side}.png`) })
      await page.getByRole('button', { name: '关闭图层编辑', exact: true }).click()
    }
    await page.locator('.inline-color-object').evaluate(el => el.removeAttribute('style'))
    await page.locator('.integration-content').evaluate(el => el.style.removeProperty('z-index'))
    await page.getByRole('button', { name: '选择已分层元素', exact: true }).dblclick()
    await page.getByRole('button', { name: '编辑', exact: true }).click()
    await page.setViewportSize({ width: 960, height: 640 })
    await page.screenshot({ path: join(evidence,'05-compact.png') })
    const bounds = await region.boundingBox(); assert(bounds.x>=12 && bounds.y>=12 && bounds.y+bounds.height<=628)
    await page.getByRole('button', { name: '预设颜色 #F44336', exact: true }).click()
    await page.getByRole('button', { name: '关闭图层编辑', exact: true }).click()
    await page.getByRole('button', { name: '继续编辑', exact: true }).click()
    await page.getByRole('button', { name: '关闭图层编辑', exact: true }).click()
    await page.getByRole('button', { name: '放弃本次换色并关闭', exact: true }).click()
    await page.getByRole('button', { name: '3D 展开', exact: true }).click()
    await page.locator('canvas.projection-three-canvas').waitFor(); await page.waitForTimeout(1000)
    await page.locator('.stage').screenshot({ path: join(evidence,'04-colored-explode.png') })
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
    assert.equal(overflow,false)
    await app.close(); app = await electron.launch(options)
    page = await app.firstWindow(); page.on('pageerror', e => errors.push(String(e)))
    await page.getByRole('button', { name: '去背景与分层', exact: true }).click()
    await page.getByRole('button', { name: '选择已分层元素', exact: true }).dblclick()
    await page.getByRole('button', { name: '编辑', exact: true }).click()
    const restored = await page.evaluate(id => window.electronAPI.fabrication.colors(id), job.id)
    assert.equal(restored.layers[1].hex,'#112233')
    assert.equal(readFileSync(join(profile,'fabrication-jobs',job.id,'view.json'),'utf8'),readFileSync(join(source,'view.json'),'utf8'))
    assert.deepEqual(errors, [])
    writeFileSync(join(evidence,'checks.json'),JSON.stringify({ errors, overflow, sourceJob:job.id,
      genuineSavedGeometry:true, algorithmRerun:false, originalResultUnchanged:true, canvasAspectRatio:ratio,
      palette:true, rgb:true, wheel:true, wholeLayerOnly:true, restartPersistence:true, adaptiveSides:true,
      listTopFirst:true, dirtyCloseConfirmation:true, editorDoubleClickEdit:process.env.E2E_EDITOR === 'true',
      screenshots:[1180,1440,960], before, restored },null,2))
    console.log('SXY_UI_AND_LAYER_RECOLOR_PASS')
  } finally { await app.close() }
}
main().catch(e => { console.error(e); process.exitCode=1 })
